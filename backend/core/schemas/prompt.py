GENERIC_SYSTEM = "你是多智能体 RAG 系统的一个执行角色，只依据证据与任务说明工作。"


def system_for(role: str) -> str:
    return {
        "planner": PLANNER_SYSTEM,
        "analyst": ANALYST_SYSTEM,
        "critic": CRITIC_SYSTEM,
        "writer": CONFIDENCE_SYSTEM,
    }.get(role, GENERIC_SYSTEM)
